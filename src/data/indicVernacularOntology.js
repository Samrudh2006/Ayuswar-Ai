/**
 * Real-time Semantic Indic Token Resolver
 * Analyzes raw colloquial spoken text and resolves matched ICD-10 & SNOMED entities
 */
export function resolveIndicVernacular(text) {
  if (!text || typeof text !== 'string') return [];
  const normalized = text.toLowerCase();

  return INDIC_VERNACULAR_ONTOLOGY.filter(item => {
    const vernacularMatch = normalized.includes(item.vernacular.toLowerCase());
    const transliterationMatch = item.transliteration.toLowerCase().split(' ').some(word => word.length > 3 && normalized.includes(word));
    const termMatch = normalized.includes(item.clinicalTerm.toLowerCase()) || normalized.includes(item.icd10.toLowerCase());
    return vernacularMatch || transliterationMatch || termMatch;
  });
}
